def run(code: str, stdin: str | None = None, expect_error: bool = False, cwd: str | None = None) -> str:
    r = subprocess.run(
        ["python3", "-c", code],
        input=stdin,
        capture_output=True,
        text=True,
        cwd=cwd,
    )
    if expect_error:
        err = (r.stderr or "").strip().splitlines()
        if r.returncode == 0:
            raise RuntimeError(f"expected error but ok:\n{code}\nOUT:{r.stdout!r}")
        return (err[-1] + "\n") if err else ""
    if r.returncode != 0:
        raise RuntimeError(f"failed:\n{code}\n{r.stderr}")
    return r.stdout


def ex(intro: str, code: str, explain: str, stdin: str | None = None, expect_error: bool = False, cwd: str | None = None) -> dict:
    out = run(code, stdin=stdin, expect_error=expect_error, cwd=cwd)
    item = {
        "intro": intro,
        "code": code if code.endswith("\n") else code + "\n",
        "output": out,
        "explain": explain,
    }
    if stdin is not None:
        item["stdin"] = stdin
    if expect_error:
        item["expect_error"] = True
    return item


