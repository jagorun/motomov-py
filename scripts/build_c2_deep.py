def main():
    data = json.loads(DEEP.read_text())
    c1_before = hashlib.sha256(json.dumps(data["courses"][0], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    c3_before = hashlib.sha256(json.dumps(data["courses"][2], ensure_ascii=False, sort_keys=True).encode()).hexdigest()

    modules = build_modules()
    assert len(modules) == 11
    for m in modules:
        exs = next(t for t in m["tabs"] if t["id"] == "examples")["examples"]
        assert 3 <= len(exs) <= 6, (m["title"], len(exs))

    data["courses"][1]["modules"] = modules
    # keep course 2 metadata, only modules replaced
    DEEP.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")

    data2 = json.loads(DEEP.read_text())
    c1_after = hashlib.sha256(json.dumps(data2["courses"][0], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    c3_after = hashlib.sha256(json.dumps(data2["courses"][2], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    assert c1_before == c1_after, "course 1 changed during c2 build"
    assert c3_before == c3_after, "course 3 changed during c2 build"

    counts = []
    for m in data2["courses"][1]["modules"]:
        n = len(next(t for t in m["tabs"] if t["id"] == "examples")["examples"])
        counts.append((m["num"], n))
    print("ok c2 examples:", counts)
    print("c1", c1_after[:12], "c3", c3_after[:12])


if __name__ == "__main__":
    main()
