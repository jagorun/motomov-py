def code_output_fingerprint(course0: dict) -> str:
    parts = []
    for m in course0["modules"]:
        exs = next(t for t in m["tabs"] if t["id"] == "examples")["examples"]
        for e in exs:
            parts.append(e["code"])
            parts.append(e["output"])
            parts.append(str(bool(e.get("expect_error"))))
    return hashlib.sha256("\0".join(parts).encode()).hexdigest()


def main() -> None:
    data = json.loads(DEEP.read_text())
    c3_before = hashlib.sha256(json.dumps(data["courses"][2], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    c2_before = hashlib.sha256(json.dumps(data["courses"][1], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    fp_before = code_output_fingerprint(data["courses"][0])

    updated = 0
    for m in data["courses"][0]["modules"]:
        exs = next(t for t in m["tabs"] if t["id"] == "examples")["examples"]
        for i, e in enumerate(exs):
            key = (m["num"], i)
            if key not in TEXTS:
                raise SystemExit(f"missing text for {key}")
            intro, explain = TEXTS[key]
            if e.get("intro") != intro or e.get("explain") != explain:
                e["intro"] = intro
                e["explain"] = explain
                updated += 1

    fp_after = code_output_fingerprint(data["courses"][0])
    assert fp_before == fp_after, "code/output of course 1 changed"
    data_out = data
    DEEP.write_text(json.dumps(data_out, ensure_ascii=False, indent=2) + "\n")
    data2 = json.loads(DEEP.read_text())
    c3_after = hashlib.sha256(json.dumps(data2["courses"][2], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    c2_after = hashlib.sha256(json.dumps(data2["courses"][1], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    assert c3_before == c3_after
    assert c2_before == c2_after
    assert code_output_fingerprint(data2["courses"][0]) == fp_before
    print(f"updated {updated} intros/explains; code/output fingerprint {fp_after[:12]}")


if __name__ == "__main__":
    main()
