def main() -> None:
    data = json.loads(DEEP.read_text())
    c2_hash = hashlib.sha256(
        json.dumps(data["courses"][1], ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()
    c3_hash = hashlib.sha256(
        json.dumps(data["courses"][2], ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()

    modules = build_modules()
    assert len(modules) == 8
    for m in modules:
        exs = next(t for t in m["tabs"] if t["id"] == "examples")["examples"]
        assert 3 <= len(exs) <= 6, m["title"]

    data["courses"][0]["modules"] = modules
    DEEP.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")

    data2 = json.loads(DEEP.read_text())
    c2_hash2 = hashlib.sha256(
        json.dumps(data2["courses"][1], ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()
    c3_hash2 = hashlib.sha256(
        json.dumps(data2["courses"][2], ensure_ascii=False, sort_keys=True).encode()
    ).hexdigest()
    assert c2_hash == c2_hash2, "course 2 changed"
    assert c3_hash == c3_hash2, "course 3 changed"

    counts = []
    for m in data2["courses"][0]["modules"]:
        exs = next(t for t in m["tabs"] if t["id"] == "examples").get("examples") or []
        counts.append((m["num"], len(exs)))
    print("ok modules examples:", counts)
    print("c2", c2_hash2[:12], "c3", c3_hash2[:12])


if __name__ == "__main__":
    main()
